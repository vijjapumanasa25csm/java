package basics;

public class BasicArray {
	public static void main(String[]args) {
//dynamic array
		int x[]= {1,2,3,4,5};
		for(int i=0;i<x.length;i++){
			System.out.println(x[i]);
		}
		//for each loop
		for(int b:x) {
			System.out.println(b*2);
			
		} 
		//static array
		int y[]=new int[5];
		
		
		
}
}
